"""Versioned API routes (``/api/v1/``).

Public catalogue routes are generated by the router. Library routes are
written explicitly because they are keyed by wallpaper slug rather than by an
interaction primary key, and they always operate on the authenticated user.
"""

from django.urls import include, path
from rest_framework.routers import DefaultRouter

from .views import (
    CategoryViewSet,
    LikeDetailView,
    LikeListCreateView,
    SavedWallpaperDetailView,
    SavedWallpaperListCreateView,
    TagViewSet,
    WallpaperViewSet,
)

router = DefaultRouter()
router.register("categories", CategoryViewSet, basename="category")
router.register("tags", TagViewSet, basename="tag")
router.register("wallpapers", WallpaperViewSet, basename="wallpaper")

app_name = "api"

urlpatterns = [
    path("", include(router.urls)),
    # The caller's own profile; sign-in/token endpoints live under /_allauth/.
    path("auth/", include("apps.accounts.urls")),
    path(
        "library/likes/",
        LikeListCreateView.as_view(),
        name="like-list",
    ),
    path(
        "library/likes/<slug:slug>/",
        LikeDetailView.as_view(),
        name="like-detail",
    ),
    path(
        "library/saved/",
        SavedWallpaperListCreateView.as_view(),
        name="saved-list",
    ),
    path(
        "library/saved/<slug:slug>/",
        SavedWallpaperDetailView.as_view(),
        name="saved-detail",
    ),
]
